import { expect, test } from '@playwright/test'

test('public demo records a check-in, opens an appointment and handoff, and acknowledges an alert', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('Care that connects.')
  await page.getByRole('link', { name: 'Explore Demo' }).click()
  await expect(page.getByText('Fictional demo', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Hello, Meera.' })).toBeVisible()
  await page.getByRole('button', { name: 'Taken', exact: true }).click()
  await expect(page.getByText('2 of 3 marked taken')).toBeVisible()
  await expect(page.getByRole('status')).toContainText('Check-in recorded as taken.')
  await page.getByRole('button', { name: 'View appointment' }).click()
  await expect(page.getByText('Greenview Family Clinic')).toBeVisible()
  await page.getByRole('button', { name: 'Today', exact: true }).click()
  await page.getByRole('button', { name: 'Open care summary' }).click()
  await expect(page.getByText('Record-based summary. No AI was used.')).toBeVisible()
  const source = page.locator('.summary-list li').filter({ hasText: 'Missed check-in' })
  await source.getByText('View source', { exact: true }).click()
  await expect(source.getByText('yesterday-missed')).toBeVisible()
  await page.getByRole('button', { name: 'Caregiver view' }).click()
  await page.getByRole('button', { name: 'Care circle' }).click()
  await page.getByRole('button', { name: 'Acknowledge' }).click()
  await expect(page.getByText('Acknowledged', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('mobile demo is keyboard reachable and can postpone or skip', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/demo')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Skip to content' })).toBeFocused()
  await page.getByRole('button', { name: 'Larger text' }).click()
  await expect(page.getByRole('button', { name: 'Standard text' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Remind me later' }).click()
  await expect(page.getByRole('status')).toContainText('postponed by 15 minutes')
  await page.getByRole('button', { name: 'Reset demo' }).click()
  await page.getByRole('button', { name: 'Skip', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('recorded as skipped')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
})
